"""Regenerate ci/constraints.txt: exact versions CI installs, per Python version.

pip's own resolver runs (``--dry-run --report``) in a fresh virtual environment
for each Python interpreter given, installing fastcircuit with the test, lint, release and
dev groups. Packages that resolve to the same version everywhere are pinned
once; the others get one ``python_version`` line per interpreter.

llvmlite is deliberately absent: its version depends on the platform and is
already pinned to one minor series per platform by pyproject.toml markers.

    python ci/update_constraints.py python3.11 python3.12 python3.13 python3.14
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "ci" / "constraints.txt"
GROUPS = ("test", "lint", "release", "dev")
EXCLUDE = {"fastcircuit", "llvmlite"}


def resolve(python: str) -> tuple[str, dict[str, str]]:
    with tempfile.TemporaryDirectory() as tmp:
        venv = Path(tmp) / "venv"
        subprocess.run([python, "-m", "venv", str(venv)], check=True)
        py = str(venv / "bin" / "python")
        quiet = subprocess.DEVNULL
        subprocess.run(
            [py, "-m", "pip", "install", "-q", "--upgrade", "pip>=25.1"], check=True, stdout=quiet
        )
        version = subprocess.run(
            [py, "-c", "import sys; print(f'{sys.version_info[0]}.{sys.version_info[1]}')"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
        report = Path(tmp) / "report.json"
        groups = [arg for g in GROUPS for arg in ("--group", g)]
        subprocess.run(
            [
                py,
                "-m",
                "pip",
                "install",
                "-q",
                "--dry-run",
                "--ignore-installed",
                "--report",
                str(report),
                str(ROOT),
                *groups,
            ],
            check=True,
            stdout=quiet,
        )
        installs = json.loads(report.read_text())["install"]
        pins = {
            item["metadata"]["name"].lower().replace("_", "-"): item["metadata"]["version"]
            for item in installs
        }
        return version, {k: v for k, v in pins.items() if k not in EXCLUDE}


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(map(int, version.split(".")))


def main(pythons: list[str]) -> None:
    resolved = dict(resolve(p) for p in pythons)
    names = sorted({name for pins in resolved.values() for name in pins})
    lines = [
        "# Generated by ci/update_constraints.py; do not edit by hand.",
        f"# Resolved for Python {', '.join(sorted(resolved, key=_version_key))}.",
        "# llvmlite is pinned per platform in pyproject.toml, not here.",
    ]
    for name in names:
        versions = {py: pins.get(name) for py, pins in resolved.items()}
        present = {py: v for py, v in versions.items() if v}
        if len(set(present.values())) == 1 and len(present) == len(resolved):
            lines.append(f"{name}=={next(iter(present.values()))}")
            continue
        for py, version in sorted(present.items(), key=lambda kv: _version_key(kv[0])):
            lines.append(f'{name}=={version}; python_version == "{py}"')
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT} ({len(names)} packages, Python {', '.join(resolved)})")


if __name__ == "__main__":
    main(sys.argv[1:] or [f"python3.{m}" for m in range(11, 15)])
