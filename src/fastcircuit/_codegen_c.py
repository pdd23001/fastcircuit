def _c_string(text: str) -> str:
    """Encode text as a C string literal; escapes quotes, '?' (trigraphs), non-ASCII."""
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '"\\?':
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def _float_literal(value: float) -> str:
    # Hexadecimal literals are exact; decimal would rely on the C parser's rounding.
    return f"({value.hex()})"


class CGenerator:
    def __init__(self, fn: ir.Function) -> None:
        self.fn = fn
        self.lines: list[str] = []
        self.depth = 1
        self.counter = 0
        self.names: dict[tuple[str, str], str] = {}
        self.arrays: list[str] = []
        for i, p in enumerate(fn.params):
            cname = f"b_{i}" if p.type in ir.ARRAYS else f"a_{i}"
            self.names[("arg", p.name)] = cname
            if p.type in ir.ARRAYS:
                self.arrays.append(cname)
        self.loop_names: dict[str, list[str]] = {}
        self.tags: dict[str, str] = {}  # anyfloat locals: nonzero while holding an np.float64
        for i, (name, t) in enumerate(fn.locals.items()):
            self.names[("local", name)] = f"l_{i}"
            if t == "anyfloat":
                self.tags[name] = f"g_{i}"

    # -- emission helpers ----------------------------------------------------
    def emit(self, line: str) -> None:
        self.lines.append("    " * self.depth + line)

    def open(self, line: str) -> None:
        self.emit(line)
        self.depth += 1

    def close(self, line: str = "}") -> None:
        self.depth -= 1
        self.emit(line)

    def fresh(self, prefix: str) -> str:
        self.counter += 1
        return f"{prefix}{self.counter}"

    def fail(self, exc: str, line: int, message: str) -> str:
        return f"{{ fc_fail({exc}, {line}, {_c_string(message)}); goto fail; }}"

    # -- expressions ---------------------------------------------------------
    def var(self, v: ir.Var) -> str:
        if v.kind == "loop":
            return self.loop_names[v.name][-1]
        return self.names[(v.kind, v.name)]

    def expr(self, e: ir.Expr) -> str:
        if isinstance(e, ir.Const):
            if e.type == "int":
                return f"({int(e.value)}LL)" if e.value != -(2**63) else "(LLONG_MIN)"
            return _float_literal(float(e.value))
        if isinstance(e, ir.Var):
            return self.var(e)
        if isinstance(e, ir.ToFloat):
            return f"((double){self.expr(e.operand)})"
        if isinstance(e, ir.Len):
            return f"((long long){self.var(e.array)}.shape[{e.axis}])"
        if isinstance(e, ir.Unary):
            return self.unary(e)
        if isinstance(e, ir.Binary):
            return self.binary(e)
        if isinstance(e, ir.Index):
            return self.index(e)
        if isinstance(e, ir.Compare):
            return self.compare(e)
        if isinstance(e, ir.Truth):
            zero = "0LL" if e.operand.type in ir.INTS else "0.0"
            return f"({self.expr(e.operand)} != {zero})"
        if isinstance(e, ir.BoolOp):
            return self.boolop(e)
        if isinstance(e, ir.IfExp):
            return self.ifexp(e)
        if isinstance(e, ir.Call):
            return self.call(e)
        if isinstance(e, ir.UFunc):
            return self.ufunc(e)
        raise NotImplementedError(f"C backend: {type(e).__name__}")  # pragma: no cover

    def ctype(self, t: ir.Type) -> str:
        return "long long" if t in ir.INTS else "int" if t == "bool" else "double"

    def tag(self, e: ir.Expr) -> str:
        """C expression, free of side effects: nonzero if ``e`` is an np.float64."""
        if e.type != "anyfloat":
            return "1" if e.type == "float64" else "0"
        if isinstance(e, ir.Var):
            return self.tags[e.name]
        if isinstance(e, ir.Binary):
            return f"({self.tag(e.left)} | {self.tag(e.right)})"
        if isinstance(e, ir.Unary):
            return self.tag(e.operand)
        if isinstance(e, ir.Call):  # abs
            return self.tag(e.args[0])
        raise NotImplementedError(f"C backend: anyfloat {type(e).__name__}")  # pragma: no cover

    def checked(self, ctype: str, line: int, exc: str, message: str, call: str) -> str:
        """``ctype t; if (call(..., &t)) raise`` for helpers returning nonzero on error."""
        t = self.fresh("t")
        self.emit(f"{ctype} {t};")
        self.emit(f"if ({call.replace('@OUT', '&' + t)}) " + self.fail(exc, line, message))
        return t

    def unary(self, e: ir.Unary) -> str:
        operand = self.expr(e.operand)
        if e.op == "not":
            return f"(!{operand})"
        if e.type in ir.FLOATS:
            return f"(-fc_v({operand}))"
        if e.type == "int64":  # wraps; NumPy reports the overflow
            return self.np_int_wrap(operand, NEG, e.line, f"0ULL - (unsigned long long){operand}")
        return self.checked(
            "long long",
            e.line,
            "PyExc_OverflowError",
            "int64 arithmetic overflow",
            f"__builtin_sub_overflow(0LL, {operand}, @OUT)",
        )

    def zero_check(self, b: str, line: int, message: str) -> None:
        self.emit(f"if ({b} == 0) " + self.fail("PyExc_ZeroDivisionError", line, message))

    def np_int_wrap(self, x: str, code: int, line: int, wrapped: str) -> str:
        """np.int64 negation/abs: the wrapped value, and a report for LLONG_MIN."""
        t = self.fresh("t")
        self.emit(f"long long {t} = (long long)({wrapped});")
        self.emit(
            f"if ({x} == LLONG_MIN && fc_np_report_int({code}, {x}, 0, {line}) < 0) goto fail;"
        )
        return t

    def np_int_binary(self, e: ir.Binary, a: str, b: str) -> str:
        """np.int64 arithmetic: wraps on overflow, // and % by zero give 0; NumPy
        reports overflow and division by zero."""
        code = self._NP_OPS[e.op]
        report = f"fc_np_report_int({code}, {a}, {b}, {e.line}) < 0"
        t = self.fresh("t")
        if e.op in ("add", "sub", "mul"):
            o = self.fresh("o")
            self.emit(f"long long {t};")
            self.emit(f"int {o} = __builtin_{e.op}_overflow({a}, {b}, &{t});")
            self.emit(f"if ({o} && {report}) goto fail;")
        elif e.op == "floordiv":
            self.emit(f"long long {t};")
            self.open(f"if ({b} == 0 || ({a} == LLONG_MIN && {b} == -1)) {{")
            self.emit(f"{t} = {b} == 0 ? 0 : LLONG_MIN;")
            self.emit(f"if ({report}) goto fail;")
            self.close("} else {")
            self.depth += 1
            self.emit(f"(void)fc_floordiv({a}, {b}, &{t});")
            self.close()
        elif e.op == "mod":
            self.emit(f"long long {t} = {b} == 0 ? 0 : fc_mod({a}, {b});")
            self.emit(f"if ({b} == 0 && {report}) goto fail;")
        else:  # pow, literal exponent
            self.emit(f"long long {t} = fc_ipow_wrap({a}, {b});")
        return t

    def binary(self, e: ir.Binary) -> str:
        a, b = self.expr(e.left), self.expr(e.right)
        if e.type == "int64":
            return self.np_int_binary(e, a, b)
        if e.type == "float64":
            return self.np_binary(e, a, b)
        if e.type == "anyfloat":  # NumPy's rules if either operand holds an np.float64
            r = self.fresh("t")
            self.emit(f"double {r};")
            self.open(f"if ({self.tag(e)}) {{")
            self.emit(f"{r} = {self.np_binary(e, a, b)};")
            self.close("} else {")
            self.depth += 1
            self.emit(f"{r} = {self.py_binary(e, a, b)};")
            self.close()
            return r
        return self.py_binary(e, a, b)

    _NP_OPS = {"add": 0, "sub": 1, "mul": 2, "truediv": 3, "floordiv": 4, "mod": 5, "pow": 6}

    def np_binary(self, e: ir.Binary, a: str, b: str) -> str:
        """np.float64 arithmetic: never raises; unusual results go to NumPy to report."""
        t = self.fresh("t")
        if e.op == "pow":
            b = f"(double){b}"
            self.emit(f"double {t} = pow({a}, {b});")
            unusual = f"fc_np_unusual({t}, {a}, {b}, 1)"
        elif e.op in ("floordiv", "mod"):
            q = self.fresh("q")
            self.emit(f"double {t} = fc_np_{e.op}(fc_v({a}), fc_v({b}));")
            self.emit(
                f"double {q} = fc_v({a}) / fc_v({b});  /* NumPy computes this quotient too */"
            )
            unusual = f"(!isfinite({t}) || !isfinite({q}) || (fabs({q}) < DBL_MIN && {a} != 0.0))"
        else:
            symbol = {"add": "+", "sub": "-", "mul": "*", "truediv": "/"}[e.op]
            self.emit(f"double {t} = fc_v({a}) {symbol} fc_v({b});")
            unusual = f"fc_np_unusual({t}, {a}, {b}, {int(e.op in ('mul', 'truediv'))})"
        self.emit(
            f"if ({unusual} && fc_np_report({self._NP_OPS[e.op]}, {a}, {b}, {e.line}) < 0) "
            "goto fail;"
        )
        return t

    def py_binary(self, e: ir.Binary, a: str, b: str) -> str:
        """Python int and float arithmetic, raising where Python raises."""
        overflow = ("PyExc_OverflowError", "int64 arithmetic overflow")
        if e.op == "pow":
            if e.type == "int":
                return self.checked("long long", e.line, *overflow, f"fc_ipow({a}, {b}, @OUT)")
            # CPython float_pow: an infinite result from a finite base is an error.
            t = self.fresh("t")
            self.emit(f"double {t} = pow({a}, (double){b});")
            self.emit(
                f"if (isinf({t}) && isfinite({a})) "
                + self.fail("PyExc_OverflowError", e.line, "float power overflow")
            )
            return t
        if e.type == "int":
            if e.op in ("add", "sub", "mul"):
                return self.checked(
                    "long long", e.line, *overflow, f"__builtin_{e.op}_overflow({a}, {b}, @OUT)"
                )
            self.zero_check(b, e.line, "integer division or modulo by zero")
            if e.op == "mod":
                t = self.fresh("t")
                self.emit(f"long long {t} = fc_mod({a}, {b});")
                return t
            return self.checked("long long", e.line, *overflow, f"fc_floordiv({a}, {b}, @OUT)")
        # float result
        if e.op in ("add", "sub", "mul"):
            symbol = {"add": "+", "sub": "-", "mul": "*"}[e.op]
            return f"(fc_v({a}) {symbol} fc_v({b}))"
        t = self.fresh("t")
        if e.op == "truediv" and e.left.type == "int":
            self.zero_check(b, e.line, "division by zero")
            self.emit(
                f"if (!fc_exact_in_double({a}) || !fc_exact_in_double({b})) "
                + self.fail(
                    "PyExc_OverflowError",
                    e.line,
                    "int operands of '/' must lie within +-2**53 for exact division",
                )
            )
            self.emit(f"double {t} = (double){a} / (double){b};")
            return t
        message = {
            "truediv": "division by zero",
            "floordiv": "float floor division by zero",
            "mod": "float modulo by zero",
        }[e.op]
        self.zero_check(b, e.line, message)
        expr = {
            "truediv": f"fc_v({a}) / fc_v({b})",
            "floordiv": f"fc_floordiv_py(fc_v({a}), fc_v({b}))",
            "mod": f"fc_fmod_py(fc_v({a}), fc_v({b}))",
        }[e.op]
        self.emit(f"double {t} = {expr};")
        return t

    def index(self, e: ir.Index) -> str:
        view = self.var(e.array)

        def evaluate(index: ir.Expr) -> str:
            o = self.fresh("o")
            self.emit(f"long long {o} = {self.expr(index)};")
            return o

        def check(axis: int, o: str) -> str:
            k, n = self.fresh("k"), f"((long long){view}.shape[{axis}])"
            self.emit(f"long long {k} = {o} < 0 ? {o} + {n} : {o};")
            self.emit(
                f"if ({k} < 0 || {k} >= {n}) {{ PyErr_Format(PyExc_IndexError, "
                f'"index %lld is out of bounds for axis {axis} with size %lld '
                f'(%s, line %d, in %s)", {o}, {n}, FC_FILE, {e.line}, FC_FUNC); goto fail; }}'
            )
            return k

        if e.chained:  # a[i][j]: row i is checked before j is evaluated
            ks = [check(0, evaluate(e.indices[0])), check(1, evaluate(e.indices[1]))]
        else:
            originals = [evaluate(index) for index in e.indices]
            ks = [check(axis, o) for axis, o in enumerate(originals)]
        offset = ks[0] if len(ks) == 1 else f"{ks[0]} * {view}.shape[1] + {ks[1]}"
        ctype = self.ctype(e.type)
        t = self.fresh("t")
        self.emit(f"{ctype} {t} = ((const {ctype} *){view}.buf)[{offset}];")
        return t

    _CMP = {"lt": "<", "le": "<=", "gt": ">", "ge": ">=", "eq": "==", "ne": "!="}
    # Mixed int/float comparisons use an exact three-way helper; 2 means NaN
    # (unordered), for which only '!=' holds, as in Python.
    _CMP3 = {
        "lt": "{c} == -1",
        "le": "({c} == -1 || {c} == 0)",
        "gt": "{c} == 1",
        "ge": "({c} == 1 || {c} == 0)",
        "eq": "{c} == 0",
        "ne": "{c} != 0",
    }

    def cmp(self, op: str, left: ir.Expr, a: str, right: ir.Expr, b: str) -> str:
        int_left = left.type in ir.INTS
        if int_left == (right.type in ir.INTS):
            return f"({a} {self._CMP[op]} {b})"
        # an int type vs a float type. Python compares an int exactly; NumPy (an
        # np.int64, or an np.float64 on the other side) converts to double first.
        x, y = (f"(double){a}", b) if int_left else (a, f"(double){b}")
        numpy = f"({x} {self._CMP[op]} {y})"
        if (left if int_left else right).type == "int64":
            return numpy
        c = self.fresh("k")
        helper = "fc_cmp_ll_d" if int_left else "fc_cmp_d_ll"
        self.emit(f"int {c} = {helper}({a}, {b});")
        exact = "(" + self._CMP3[op].format(c=c) + ")"
        tag = self.tag(right if int_left else left)
        return exact if tag == "0" else numpy if tag == "1" else f"({tag} ? {numpy} : {exact})"

    def compare(self, e: ir.Compare) -> str:
        first = e.operands[0]
        a = self.expr(first)
        if len(e.ops) == 1:
            right = e.operands[1]
            return self.cmp(e.ops[0], first, a, right, self.expr(right))
        # Chained: later operands are evaluated only while the chain holds.
        r = self.fresh("c")
        self.emit(f"int {r} = 0;")
        opened = 0
        left = first
        for i, (op, right) in enumerate(zip(e.ops, e.operands[1:], strict=True)):
            b = self.expr(right)
            self.emit(f"{r} = {self.cmp(op, left, a, right, b)};")
            if i < len(e.ops) - 1:
                self.open(f"if ({r}) {{")
                opened += 1
            left, a = right, b
        for _ in range(opened):
            self.close()
        return r

    def boolop(self, e: ir.BoolOp) -> str:
        r = self.fresh("c")
        self.emit(f"int {r} = 0;")
        opened = 0
        for i, value in enumerate(e.values):
            self.emit(f"{r} = {self.expr(value)};")
            if i < len(e.values) - 1:
                self.open(f"if ({r}) {{" if e.op == "and" else f"if (!{r}) {{")
                opened += 1
        for _ in range(opened):
            self.close()
        return r

    def ifexp(self, e: ir.IfExp) -> str:
        r = self.fresh("t")
        self.emit(f"{self.ctype(e.type)} {r};")
        self.open(f"if ({self.expr(e.test)}) {{")
        self.emit(f"{r} = {self.expr(e.body)};")
        self.close("} else {")
        self.depth += 1
        self.emit(f"{r} = {self.expr(e.orelse)};")
        self.close()
        return r

    def call(self, e: ir.Call) -> str:
        args = [self.expr(a) for a in e.args]  # Python evaluates every argument first
        if e.func == "abs":
            if e.type in ir.FLOATS:
                return f"fabs({args[0]})"
            if e.type == "int64":
                x = args[0]
                return self.np_int_wrap(
                    x, ABS, e.line, f"{x} < 0 ? 0ULL - (unsigned long long){x} : {x}"
                )
            self.emit(
                f"if ({args[0]} == LLONG_MIN) "
                + self.fail("PyExc_OverflowError", e.line, "int64 arithmetic overflow")
            )
            return f"({args[0]} < 0 ? -{args[0]} : {args[0]})"
        if e.func in ("min", "max"):
            # Python keeps the first item unless a later one compares strictly
            # smaller (min) or larger (max); this also fixes NaN behaviour.
            r = self.fresh("t")
            self.emit(f"{self.ctype(e.type)} {r} = {args[0]};")
            op = "<" if e.func == "min" else ">"
            for a in args[1:]:
                self.emit(f"if ({a} {op} {r}) {r} = {a};")
            return r
        if e.func == "int" and e.args[0].type == "int64":
            return args[0]  # int(np.int64)
        if e.func in ("int", "floor", "ceil"):
            fn = {"int": "trunc", "floor": "floor", "ceil": "ceil"}[e.func]
            t = self.fresh("t")
            self.emit(f"long long {t};")
            self.emit(f"if (fc_to_ll({fn}({args[0]}), {e.line}, &{t}) < 0) goto fail;")
            return t
        t = self.fresh("t")
        self.emit(f"double {t};")
        if len(args) == 2:
            self.emit(
                f"if (fc_math2({e.func}, {args[0]}, {args[1]}, {e.line}, &{t}) < 0) goto fail;"
            )
            return t
        can_overflow = int(MATH_1[e.func])
        self.emit(
            f"if (fc_math1({e.func}, {args[0]}, {can_overflow}, {e.line}, &{t}) < 0) goto fail;"
        )
        return t

    def ufunc(self, e: ir.UFunc) -> str:
        """A NumPy math function through its own float64 loop; unusual results go to
        NumPy to report, as for np.float64 arithmetic."""
        names = []
        for arg in e.args:  # Python evaluates every argument first
            v = self.fresh("u")
            self.emit(f"double {v} = {self.expr(arg)};")
            names.append(v)
        self.emit("if (!fc_ufuncs_ready && fc_init_ufuncs() < 0) goto fail;")
        t = self.fresh("t")
        call = f"fc_ufunc{len(names)}({e.index}, {', '.join(names)})"
        self.emit(f"double {t} = {call};  /* np.{e.name} */")
        a, b = names[0], names[1] if len(names) == 2 else "0.0"
        self.emit(
            f"if (fc_np_unusual_call({t}, {a}, {b}) && "
            f"fc_np_report({UFUNC_BASE + e.index}, {a}, {b}, {e.line}) < 0) goto fail;"
        )
        return t

    # -- statements ----------------------------------------------------------
    def stmts(self, body: tuple[ir.Stmt, ...]) -> None:
        for s in body:
            self.stmt(s)

    def stmt(self, s: ir.Stmt) -> None:
        if isinstance(s, ir.For):
            self.for_loop(s)
        elif isinstance(s, ir.If):
            self.open(f"{{ /* line {s.line}: if */")
            cond = self.expr(s.test)
            # Single comparisons are already parenthesised (clang -Wparentheses-equality).
            if not cond.startswith("(") or not (
                isinstance(s.test, ir.Compare) and len(s.test.ops) == 1
            ):
                cond = f"({cond})"
            self.open(f"if {cond} {{")
            self.stmts(s.body)
            if s.orelse:
                self.close("} else {")
                self.depth += 1
                self.stmts(s.orelse)
            self.close()
            self.close()
        elif isinstance(s, ir.Gate):
            self.gate(s)
        elif isinstance(s, ir.Assign):
            value = self.expr(s.value)
            if s.target.type == "anyfloat":
                self.emit(
                    f"{{ double v = {value}; int g = {self.tag(s.value)}; "
                    f"{self.var(s.target)} = v; {self.tags[s.target.name]} = g; }}"
                    f"  /* line {s.line} */"
                )
            else:
                self.emit(f"{self.var(s.target)} = {value};  /* line {s.line} */")
        elif isinstance(s, (ir.Measure, ir.Reset)):
            self.measure_or_reset(s)
        else:  # pragma: no cover
            raise NotImplementedError(f"C backend: {type(s).__name__}")

    def for_loop(self, s: ir.For) -> None:
        self.open(f"{{ /* line {s.line}: for {s.var} in range(...) */")
        start, stop, step = (self.fresh(p) for p in ("start", "stop", "step"))
        # Python evaluates all range() arguments before validating the step.
        self.emit(f"long long {start} = {self.expr(s.start)};")
        self.emit(f"long long {stop} = {self.expr(s.stop)};")
        self.emit(f"long long {step} = {self.expr(s.step)};")
        self.emit(
            f"if ({step} == 0) "
            + self.fail("PyExc_ValueError", s.line, "range() arg 3 must not be zero")
        )
        i = self.fresh("i")
        self.loop_names.setdefault(s.var, []).append(i)
        self.open(f"for (long long {i} = {start}; {step} > 0 ? {i} < {stop} : {i} > {stop};) {{")
        self.emit(
            "if (++iterations > FC_MAX_ITERATIONS) "
            + self.fail("PyExc_ValueError", s.line, "loop iteration limit exceeded")
        )
        self.emit("if ((iterations & 16383) == 0 && PyErr_CheckSignals() < 0) goto fail;")
        self.stmts(s.body)
        self.emit("/* overflow of the next value means it lies beyond any int64 stop */")
        self.emit(f"if (__builtin_add_overflow({i}, {step}, &{i})) break;")
        self.close()
        self.loop_names[s.var].pop()
        self.close()

    def bit_index(self, var: str, size: str, line: int, exc: str = "fc_QubitIndexError") -> None:
        orig = self.fresh("o")
        self.emit(f"long long {orig} = {var};")
        self.emit(f"if ({var} < 0) {var} += {size};")
        self.emit(
            f"if ({var} < 0 || {var} >= {size}) {{ PyErr_Format({exc}, "
            f'"Index %lld out of range for size %lld (%s, line %d, in %s)", '
            f"{orig}, {size}, FC_FILE, {line}, FC_FUNC); goto fail; }}"
        )

    def measure_or_reset(self, s: ir.Measure | ir.Reset) -> None:
        name = "measure" if isinstance(s, ir.Measure) else "reset"
        self.open(f"{{ /* line {s.line}: {name} */")
        q = self.fresh("q")
        self.emit(f"long long {q} = {self.expr(s.qubit)};")
        c = None
        if isinstance(s, ir.Measure):
            c = self.fresh("c")
            self.emit(f"long long {c} = {self.expr(s.clbit)};")
        self.bit_index(q, "nq", s.line)
        if c is not None:
            self.bit_index(c, "nc", s.line)
        self.emit(
            "if (++gates > FC_MAX_GATES) "
            + self.fail("PyExc_ValueError", s.line, "gate limit exceeded")
        )
        if c is not None:
            call = f"qk_circuit_measure(circuit, (uint32_t){q}, (uint32_t){c})"
        else:
            call = f"qk_circuit_reset(circuit, (uint32_t){q})"
        self.emit(f"QkExitCode rc = {call};")
        self.emit(
            "if (rc != QkExitCode_Success) { PyErr_Format(PyExc_RuntimeError, "
            f'"Qiskit rejected {name} (exit code %d) (%s, line %d, in %s)", '
            f"(int)rc, FC_FILE, {s.line}, FC_FUNC); goto fail; }}"
        )
        self.close()

    def gate(self, s: ir.Gate) -> None:
        self.open(f"{{ /* line {s.line}: {s.name} */")
        # Evaluate every argument first, in order, as Python does before Qiskit
        # validates the qubits.
        params = []
        for e in s.params:
            p = self.fresh("p")
            self.emit(f"double {p} = {self.expr(e)};")
            params.append(p)
        qubits = []
        for e in s.qubits:
            q = self.fresh("q")
            self.emit(f"long long {q} = {self.expr(e)};")
            qubits.append(q)
        for q in qubits:
            self.bit_index(q, "nq", s.line)
        for j, qj in enumerate(qubits):
            for qk in qubits[:j]:
                self.emit(
                    f"if ({qj} == {qk}) "
                    + self.fail("fc_DuplicateQubitError", s.line, "duplicate qubit arguments")
                )
        self.emit(
            "if (++gates > FC_MAX_GATES) "
            + self.fail("PyExc_ValueError", s.line, "gate limit exceeded")
        )
        self.emit("const uint32_t qs[] = {" + ", ".join(f"(uint32_t){q}" for q in qubits) + "};")
        ps = "NULL"
        if params:
            self.emit("const double ps[] = {" + ", ".join(params) + "};")
            ps = "ps"
        self.emit(f"QkExitCode rc = qk_circuit_gate(circuit, QkGate_{s.enum}, qs, {ps});")
        self.emit(
            "if (rc != QkExitCode_Success) { PyErr_Format(PyExc_RuntimeError, "
            f'"Qiskit rejected gate {s.name} (exit code %d) (%s, line %d, in %s)", '
            f"(int)rc, FC_FILE, {s.line}, FC_FUNC); goto fail; }}"
        )
        self.close()

    # -- function ------------------------------------------------------------
    def arguments(self) -> None:
        fn = self.fn
        first = 1  # args[0] is the circuit the block appends to
        expected = len(fn.params) + first
        self.emit(
            f"if (nargs != {expected}) {{ PyErr_Format(PyExc_TypeError, "
            f'"expected {expected} arguments, got %zd (in %s)", nargs, FC_FUNC); '
            "goto fail; }"
        )
        for i, p in enumerate(fn.params, start=first):
            c = self.names[("arg", p.name)]
            name = _c_string(p.name)
            if p.type == "int":
                self.emit(
                    f"if (!PyLong_CheckExact(args[{i}])) {{ PyErr_Format(PyExc_TypeError, "
                    f'"%s must be a Python int (in %s)", {name}, FC_FUNC); goto fail; }}'
                )
                self.emit(f"{c} = PyLong_AsLongLong(args[{i}]);")
                self.emit(f"if ({c} == -1 && PyErr_Occurred()) goto fail;")
            elif p.type == "float":
                self.emit(
                    f"if (!PyFloat_CheckExact(args[{i}])) {{ PyErr_Format(PyExc_TypeError, "
                    f'"%s must be a Python float (in %s)", {name}, FC_FUNC); goto fail; }}'
                )
                self.emit(f"{c} = PyFloat_AS_DOUBLE(args[{i}]);")
            elif p.type == "int64":  # converted through np.int64.__index__
                self.emit(f"{c} = PyLong_AsLongLong(args[{i}]);")
                self.emit(f"if ({c} == -1 && PyErr_Occurred()) goto fail;")
            elif p.type == "float64":  # np.float64 subclasses float
                self.emit(
                    f"if (!PyFloat_Check(args[{i}])) {{ PyErr_Format(PyExc_TypeError, "
                    f'"%s must be an np.float64 (in %s)", {name}, FC_FUNC); goto fail; }}'
                )
                self.emit(f"{c} = PyFloat_AS_DOUBLE(args[{i}]);")
            else:
                element, ndim = ir.ARRAYS[p.type]
                ints = int(element == "int64")
                self.emit(
                    f"if (fc_get_array(args[{i}], &{c}, {name}, {ndim}, {ints}) < 0) goto fail;"
                )

    def generate_body(self) -> str:
        fn = self.fn
        decls = []
        for p in fn.params:
            c = self.names[("arg", p.name)]
            ctype = "Py_buffer" if p.type in ir.ARRAYS else self.ctype(p.type)
            init = " = {0}" if p.type in ir.ARRAYS else " = 0"
            decls.append(f"{ctype} {c}{init}; /* {p.name}: {p.type} */")
        for name, t in fn.locals.items():
            decls.append(f"{self.ctype(t)} {self.names[('local', name)]} = 0; /* {name}: {t} */")
            if t == "anyfloat":
                decls.append(f"int {self.tags[name]} = 0; /* {name} holds an np.float64 */")

        self.arguments()
        self.emit(
            "if (Py_TYPE(args[0]) != (PyTypeObject *)fc_QuantumCircuit) { "
            'PyErr_Format(PyExc_TypeError, "expected a QuantumCircuit (in %s)", FC_FUNC); '
            "goto fail; }"
        )
        self.open(f"{{ /* line {fn.line}: sizes of the circuit */")
        self.emit("PyObject *size = NULL;")
        for var, attr in (("nq", "num_qubits"), ("nc", "num_clbits")):
            self.emit(f'size = PyObject_GetAttrString(args[0], "{attr}");')
            self.emit("if (size == NULL) goto fail;")
            self.emit(f"{var} = PyLong_AsLongLong(size);")
            self.emit("Py_DECREF(size);")
            self.emit(f"if ({var} == -1 && PyErr_Occurred()) goto fail;")
        self.close()
        self.emit(
            "if (nq > FC_MAX_QUBITS) "
            + self.fail("PyExc_ValueError", fn.line, "qubit count exceeds fastcircuit limit")
        )
        self.emit(
            "if (nc > FC_MAX_CLBITS) "
            + self.fail("PyExc_ValueError", fn.line, "clbit count exceeds fastcircuit limit")
        )
        self.emit("result = args[0];  /* returned to the caller, so take a reference */")
        self.emit("Py_INCREF(result);")
        self.emit(
            "/* `data` stays referenced until return, so the borrowed pointer stays valid. */"
        )
        self.emit('data = PyObject_GetAttrString(result, "_data");')
        self.emit("if (data == NULL) goto fail;")
        self.emit("circuit = qk_circuit_borrow_from_python(data);")
        self.emit("if (circuit == NULL) goto fail;")
        self.open("{ /* function body */")
        self.stmts(fn.body)
        self.close()
        body = self.lines

        release = [f"    if ({b}.obj != NULL) PyBuffer_Release(&{b});" for b in self.arrays]
        out = [
            "",
            f"/* Compiled from {fn.qualname} ({fn.filename}, line {fn.line}). */",
            "static PyObject *fc_run(PyObject *self, PyObject *const *args, Py_ssize_t nargs) {",
            "    (void)self;",
            "    PyObject *result = NULL, *data = NULL;",
            "    QkCircuit *circuit = NULL;",
            "    long long nq = 0, nc = 0, iterations = 0, gates = 0;",
            "    (void)nc; (void)iterations; (void)gates; (void)circuit;",
            *("    " + d for d in decls),
            *body,
            "    Py_DECREF(data);",
            *release,
            "    return result;",
            "fail:",
            "    Py_XDECREF(data);",
            "    Py_XDECREF(result);",
            *release,
            "    return NULL;",
            "}",
            "",
            "static PyMethodDef fc_methods[] = {",
            '    {"run", (PyCFunction)(void (*)(void))fc_run, METH_FASTCALL, NULL},',
            "    {NULL, NULL, 0, NULL},",
            "};",
        ]
        preamble = PREAMBLE % {
            "max_qubits": MAX_QUBITS,
            "max_clbits": MAX_CLBITS,
            "max_gates": MAX_GATES,
            "max_iterations": MAX_ITERATIONS,
            "nufuncs": len(UFUNCS),
            "file": _c_string(fn.filename),
            "func": _c_string(fn.qualname),
        }
        return preamble + "\n".join(out) + "\n"


def generate_body(fn: ir.Function) -> str:
    """C source without the module-init function (input to the cache key)."""
    return CGenerator(fn).generate_body()


def module_init(module: str, key: str) -> str:
    return f"""
static struct PyModuleDef fc_module = {{
    PyModuleDef_HEAD_INIT, "{module}", NULL, -1, fc_methods, NULL, NULL, NULL, NULL,
}};

PyMODINIT_FUNC PyInit_{module}(void);
PyMODINIT_FUNC PyInit_{module}(void) {{
    if (qk_import() < 0) return NULL;
    /* Headers and runtime library must be the same Qiskit build. Qiskit's
       qk_api_version macro casts to a prototype-less pointer `uint32_t(*)()`; the
       warning comes from the header macro, so it is silenced only here. */
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wstrict-prototypes"
    uint32_t runtime_version = qk_api_version();
#pragma GCC diagnostic pop
    if (runtime_version != (uint32_t)QISKIT_VERSION_HEX) {{
        PyErr_Format(PyExc_ImportError,
                     "fastcircuit module built for Qiskit C API 0x%08x, runtime is 0x%08x",
                     (unsigned)QISKIT_VERSION_HEX, (unsigned)runtime_version);
        return NULL;
    }}
    PyObject *mod = PyImport_ImportModule("qiskit");
    if (mod == NULL) return NULL;
    fc_QuantumCircuit = PyObject_GetAttrString(mod, "QuantumCircuit");
    Py_DECREF(mod);
    if (fc_QuantumCircuit == NULL) return NULL;
    mod = PyImport_ImportModule("fastcircuit.errors");
    if (mod == NULL) return NULL;
    fc_QubitIndexError = PyObject_GetAttrString(mod, "QubitIndexError");
    fc_DuplicateQubitError = PyObject_GetAttrString(mod, "DuplicateQubitError");
    Py_DECREF(mod);
    if (fc_QubitIndexError == NULL || fc_DuplicateQubitError == NULL) return NULL;
    mod = PyImport_ImportModule("fastcircuit._fperror");
    if (mod == NULL) return NULL;
    fc_report = PyObject_GetAttrString(mod, "report");
    fc_report_int = PyObject_GetAttrString(mod, "report_int");
    Py_DECREF(mod);
    if (fc_report == NULL || fc_report_int == NULL) return NULL;
    PyObject *m = PyModule_Create(&fc_module);
    if (m == NULL) return NULL;
    if (PyModule_AddStringConstant(m, "__fastcircuit_key__", "{key}") < 0) {{
        Py_DECREF(m);
        return NULL;
    }}
    return m;
}}
"""
