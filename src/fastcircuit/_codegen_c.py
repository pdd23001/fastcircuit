"""Typed IR -> C source for a CPython extension using Qiskit's C API.

Generated code is meant to be read: one block per source statement, comments with
Python line numbers, and a fixed helper preamble. Every operation that Python
could reject (overflow, zero division, bounds, duplicates, limits) is checked and
raises with the originating source line. Expression strings returned by ``expr``
are side-effect free; anything that can fail is evaluated into a temporary first,
in Python's left-to-right order.
"""

