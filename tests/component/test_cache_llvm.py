"""LLVM backend: persistent object-file cache across real processes.

Counterparts of test_cache_native.py (C backend). Every child points CC at a path
that does not exist: the LLVM backend must never need a C compiler.
"""

from __future__ import annotations

import json
import subprocess
import sys

import pytest

from support.processes import child_env as _child_env
from support.processes import run_child, start_child, write_module

pytestmark = pytest.mark.needs_llvmlite

NO_CC = "/nonexistent/cc"


def child_env(cache, **extra):
    return _child_env(cache, CC=NO_CC, **extra)  # default backend: llvm


def _objects(cache):
    return sorted((cache / "v1" / "entries").glob("*/llvm-*/kernel.o"))


def test_compile_then_reuse_in_new_process_without_compiler(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    first = run_child(tmp_path, module, child_env(cache))
    assert first["source"] == "compiled" and first["equal"]
    assert first["build_seconds"] > 0
    (obj,) = _objects(cache)
    assert (obj.parent / "kernel.ll").read_text().startswith("; Generated by fastcircuit")
    second = run_child(tmp_path, module, child_env(cache))
    assert second == {**second, "source": "persistent cache", "equal": True, "build_seconds": None}


def test_corrupted_object_is_rebuilt(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    run_child(tmp_path, module, child_env(cache))
    (obj,) = _objects(cache)
    data = bytearray(obj.read_bytes())
    data[len(data) // 2] ^= 0xFF  # same size, different content: caught by the checksum
    obj.write_bytes(bytes(data))
    result = run_child(tmp_path, module, child_env(cache))
    assert result == {**result, "source": "compiled", "equal": True}
    assert len(_objects(cache)) == 1


def test_truncated_metadata_is_rebuilt(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    run_child(tmp_path, module, child_env(cache))
    (meta,) = (cache / "v1" / "entries").glob("*/llvm-*/meta.json")
    meta.write_text(meta.read_text()[:20])
    assert run_child(tmp_path, module, child_env(cache))["source"] == "compiled"


def test_concurrent_first_calls_compile_once(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    procs = [start_child(tmp_path, module, child_env(cache)) for _ in range(6)]
    sources = []
    for proc in procs:
        out, err = proc.communicate(timeout=300)
        assert proc.returncode == 0, err
        sources.append(json.loads(out.strip().splitlines()[-1])["source"])
    assert sources.count("compiled") == 1, sources
    assert sources.count("persistent cache") == 5, sources
    assert len(_objects(cache)) == 1


def test_cache_disabled_compiles_every_process(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    env = child_env(cache, FASTCIRCUIT_NO_CACHE="1")
    for _ in range(2):
        assert run_child(tmp_path, module, env)["source"] == "compiled (cache disabled)"
    assert not _objects(cache)


@pytest.mark.needs_c_backend
def test_backends_use_separate_entries(tmp_path):
    cache = tmp_path / "cache"
    module = write_module(tmp_path)
    run_child(tmp_path, module, child_env(cache))
    c_env = _child_env(cache, FASTCIRCUIT_BACKEND="c")
    assert run_child(tmp_path, module, c_env)["source"] == "compiled"  # not the LLVM object
    assert len(_objects(cache)) == 1
    assert len(list((cache / "v1" / "entries").glob("*/*/*.so"))) == 1


def test_doctor_passes_without_a_c_compiler(monkeypatch, capsys):
    from fastcircuit.__main__ import main

    monkeypatch.delenv("FASTCIRCUIT_BACKEND", raising=False)
    monkeypatch.setenv("CC", NO_CC)
    assert main(["doctor"]) == 0
    out = capsys.readouterr().out
    assert "backend llvm" in out and "ok    LLVM (llvmlite)" in out
    assert "not needed for the default backend" in out


FALLBACK_CHILD = """\
import json, sys
sys.modules["llvmlite"] = None  # as on a platform without llvmlite wheels
sys.path.insert(0, sys.argv[1])
from fastcircuit import _block
import {module} as m
qc = m.build(5, 3, 0.25)
[(_, compiled)] = _block.compiled_blocks()
print(json.dumps({{"backend": compiled.backend, "source": compiled.timings["source"],
                  "equal": qc == m.reference(5, 3, 0.25)}}))
"""


@pytest.mark.needs_c_backend
def test_without_llvmlite_the_c_backend_is_chosen_automatically(tmp_path):
    module = write_module(tmp_path)
    proc = subprocess.run(
        [sys.executable, "-c", FALLBACK_CHILD.format(module=module), str(tmp_path)],
        env=_child_env(tmp_path / "cache"),  # FASTCIRCUIT_BACKEND unset: automatic choice
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    result = json.loads(proc.stdout.strip().splitlines()[-1])
    assert result == {"backend": "c", "source": "compiled", "equal": True}
